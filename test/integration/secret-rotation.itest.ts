/**
 * A `SECRET_KEY` rotation on a running instance, from the first row written under the old key to the
 * day the old key is deleted ([ADR-0075](../../../.ssot/ADR.md#adr-0075)).
 *
 * **Every assertion here needs a database and most of them need a half-finished one**, which is the
 * reason this file exists beside the unit tests rather than inside them. Interrupting a pass, proving
 * that a row is readable at the moment the process died, and then proving the same pass finishes when
 * it is started again are statements about rows, not about functions.
 *
 * Two things reach outside this process and neither of them reaches a network:
 *
 * - A `node:http` server on the loopback interface answers the three Confluence REST endpoints the
 *   driver uses, and **refuses anything but the exact `Authorization` header** built from the stored
 *   token. That is deliberate: `ConfluenceDriver` takes an injected client in every other test, and an
 *   injected client is precisely the seam that skips `decryptSecret`. A rotation test that used it
 *   would prove nothing about whether the credential survived. Here the product's own path runs —
 *   read the column, open it with the ring, build the Basic header — and the server is the thing that
 *   says whether the token that came out is the token that went in.
 * - The command itself is run as a child process at the end, because criterion 5 is about what the
 *   command *prints*, and `reportLines` is only most of that.
 */

