const ring = (current: string, previous?: string): SecretKeyring => ({ current, previous });

/** A `v1.` envelope exactly as `crypto.ts` wrote them before this phase: no key identity anywhere in it. */
function v1(plain: string, secretKey: string): string {
  const iv = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', createHash('sha256').update(secretKey, 'utf8').digest(), iv);
  const ct = Buffer.concat([cipher.update(plain, 'utf8'), cipher.final()]);
  return ['v1', iv.toString('base64url'), cipher.getAuthTag().toString('base64url'), ct.toString('base64url')].join('.');
}

/**
 * Every stored value in every column the registry names.
 *
 * Driven by `ENCRYPTED_FIELDS` rather than by two column names written out here, for the same reason
 * the command is: a column added later is swept by this file on the day it is added, and a column
 * dropped from the registry takes these assertions down with it.
 */
async function storedValues(): Promise<Array<{ field: EncryptedField; id: string; value: string }>> {
  const out: Array<{ field: EncryptedField; id: string; value: string }> = [];
  for (const field of ENCRYPTED_FIELDS) {
    const rows = (await db.select({ id: field.id, value: field.column }).from(field.table as PgTable)) as Array<{ id: string; value: string | null }>;
    for (const row of rows) if (row.value !== null) out.push({ field, id: row.id, value: row.value });
  }
  return out;
}

/** Opens a value the way the product opens it: the webhook column tolerates a legacy plaintext, the other does not. */
function open(entry: { field: EncryptedField; value: string }, keys: SecretKeyring): string {
  return entry.field.legacyPlaintext ? decryptWebhookSecret(entry.value, keys) : decryptSecret(entry.value, keys);
}

async function sourceRow(id: string): Promise<DocumentSourceRow> {
  const [row] = await db.select().from(documentSources).where(eq(documentSources.id, id));
  return row;
}

/** Nothing a rotation touches may appear in anything a rotation prints. */
function expectNoPlaintext(text: string): void {
  for (const secret of [
    CONFLUENCE_TOKEN,
    LEGACY_TOKEN,
    LEGACY_WEBHOOK,
    NOTION_TOKEN,
    LOST_TOKEN,
    RACE_LOSER,
    RACE_WINNER,
    gitWebhookSecret,
    OLD_KEY,
    NEW_KEY,
    LOST_KEY,
  ]) {
    if (secret) expect(text).not.toContain(secret);
  }
}

