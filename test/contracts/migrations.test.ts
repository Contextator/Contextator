import { createHash } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

/**
 * **Applied migrations are never edited** ([ADR-0137](../../.ssot/ADR.md#adr-0137), Tier 1: forward-only
 * migrations, every `1.x` upgrading every earlier `1.x` database). `migrations.lock.json` records the
 * SHA-256 of every `drizzle/*.sql` in the order `drizzle/meta/_journal.json` applies them, and it only ever
 * grows at the end:
 *
 * - a recorded migration whose bytes changed, or which is gone, is red;
 * - a `.sql` file the lock does not know is red, with the line to add — a new migration is a deliberate
 *   addition to the lock, in the same change, and (the lock being a contract file) needs a changelog entry;
 * - the lock's order must be the journal's order for as many entries as the lock has.
 *
 * The hash is of the file's bytes as committed (`.gitattributes` pins text to LF, so a checkout on any
 * platform hashes the same). The lock is not regenerated by `-u`: appending is a manual, reviewed edit.
 */

const ROOT = path.join(import.meta.dirname, '..', '..');
const DRIZZLE = path.join(ROOT, 'drizzle');
const LOCK = path.join(import.meta.dirname, 'migrations.lock.json');

interface Locked {
  tag: string;
  sha256: string;
}

const lock = JSON.parse(readFileSync(LOCK, 'utf8')) as Locked[];
const journal = (JSON.parse(readFileSync(path.join(DRIZZLE, 'meta', '_journal.json'), 'utf8')) as { entries: Array<{ tag: string }> }).entries.map(
  (entry) => entry.tag,
);
const sqlTags = readdirSync(DRIZZLE)
  .filter((file) => file.endsWith('.sql'))
  .map((file) => file.slice(0, -'.sql'.length))
  .sort();
const hashOf = (tag: string): string =>
  createHash('sha256')
    .update(readFileSync(path.join(DRIZZLE, `${tag}.sql`)))
    .digest('hex');

describe('applied migrations are locked', () => {
  it('has a lock that is not empty and records each migration once', () => {
    expect(lock.length).toBeGreaterThan(30);
    expect(new Set(lock.map((entry) => entry.tag)).size).toBe(lock.length);
    for (const entry of lock) expect(entry.sha256).toMatch(/^[0-9a-f]{64}$/);
  });

  it('finds every locked migration unchanged', () => {
    for (const { tag, sha256 } of lock) {
      expect(sqlTags, `${tag}.sql is in the lock but is no longer in drizzle/ — an applied migration is never removed or renamed`).toContain(tag);
      expect(hashOf(tag), `${tag}.sql changed after it was locked — an applied migration is never edited; add a new one instead`).toBe(sha256);
    }
  });

  it('has no migration the lock does not know', () => {
    const known = new Set(lock.map((entry) => entry.tag));
    const unlocked = sqlTags.filter((tag) => !known.has(tag));
    const hint = unlocked.map((tag) => `add to test/contracts/migrations.lock.json: { "tag": "${tag}", "sha256": "${hashOf(tag)}" }`);
    expect(unlocked, `a new migration has to be added to the lock (appended, in journal order):\n${hint.join('\n')}`).toEqual([]);
  });

  it('keeps the lock in the order the journal applies them', () => {
    expect(lock.map((entry) => entry.tag)).toEqual(journal.slice(0, lock.length));
  });
});
